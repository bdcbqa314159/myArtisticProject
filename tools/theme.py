#!/usr/bin/env python3
"""The graphiste's decisions, turned into a stylesheet.

    python3 tools/theme.py            # write static/css/theme.css
    python3 tools/theme.py --check    # fail if what is committed is stale

WHY THIS EXISTS

A palette and a typeface are the graphiste's to decide, and until now
changing either meant editing `site.css` — which is 2000 lines of
reasoning about motion, overlays and hit testing. Nobody should have to
go in there to say the ground is a different cream.

So the decisions live in `config.toml`, where the rest of the launch
settings are, and this turns them into a short stylesheet of nothing
but custom properties. It is linked AFTER `site.css`, so whatever is
set here wins and whatever is left blank keeps the value the stylesheet
already has. An empty `[extra.theme]` produces a file that changes
nothing at all — which is the state it ships in.

WHY THE VALIDATION IS STRICT

This writes CSS from values a browser can set. A value like

    red; } body { display: none } :root { --x: red

would end the rule and start another. So nothing is trusted: a colour
must look like a colour, a font stack must look like a font stack, and
anything with a brace, a semicolon, an `@` or a `url(` in it is
refused by name. And `--check` then reads the FILE BACK and fails if it
holds anything but the two rules it is allowed to have — an independent
look at the artefact that ships, rather than at the values that went in.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "config.toml"
SHEET = ROOT / "static" / "css" / "theme.css"

# The eight a palette is made of. Deliberately NOT --max, --gutter,
# --band or --track-label: those are layout and typographic rhythm,
# decided once and not a matter of taste per client.
COLOURS = ("ink", "muted", "faint", "line", "bg", "panel", "tint", "accent")

COLOUR = re.compile(r"^#(?:[0-9a-fA-F]{3}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$")

# A font stack: names, quotes, commas, spaces, hyphens. Nothing else —
# no parentheses, so no `url()`, and no semicolons or braces.
FONTS = re.compile(r'^[A-Za-z0-9 ,\'"À-ɏ-]{1,200}$')

BANNED = ("{", "}", ";", "@", "url(", "/*", "\\", "<", ">")


class Bad(Exception):
    """A value that will not be written. The message names the field."""


def section(name: str) -> "dict[str, str]":
    """One `[section]` of config.toml, as plain strings.

    Hand-read rather than parsed with a TOML library, for the same
    reason every other tool here does it: `config.toml` is mostly
    comments explaining why each switch exists, and nothing may rewrite
    it wholesale.
    """
    text = CONFIG.read_text(encoding="utf-8")
    start = text.find(f"[{name}]")
    if start == -1:
        return {}
    rest = text[start + len(name) + 2:]
    end = rest.find("\n[")
    body = rest if end == -1 else rest[:end]
    return {
        m.group(1): m.group(2)
        for m in re.finditer(r'^\s*([a-z_]+)\s*=\s*"([^"]*)"', body, re.M)
    }


def clean(field: str, value: str, kind: str) -> str:
    value = value.strip()
    if not value:
        return ""
    for bad in BANNED:
        if bad in value:
            raise Bad(f"{field}: {value!r} contains {bad!r}, which could end "
                      f"the rule and start another. Refused")
    if kind == "colour" and not COLOUR.match(value):
        raise Bad(f"{field}: {value!r} is not a colour. Write it as #rgb, "
                  f"#rrggbb or #rrggbbaa")
    if kind == "font" and not FONTS.match(value):
        raise Bad(f"{field}: {value!r} is not a font stack. Names, commas and "
                  f"quotes only")
    return value


def build() -> str:
    fonts = section("extra.theme")
    rules: "list[tuple[str, list[str]]]" = []

    top = []
    for field, prop in (("serif", "--serif"), ("sans", "--sans")):
        got = clean(f"theme.{field}", fonts.get(field, ""), "font")
        if got:
            top.append(f"  {prop}: {got};")
    for field in COLOURS:
        got = clean(f"theme.cream.{field}", section("extra.theme.cream").get(field, ""),
                    "colour")
        if got:
            top.append(f"  --{field}: {got};")
    if top:
        rules.append((":root", top))

    cool = []
    for field in COLOURS:
        got = clean(f"theme.cool.{field}", section("extra.theme.cool").get(field, ""),
                    "colour")
        if got:
            cool.append(f"  --{field}: {got};")
    if cool:
        rules.append(('[data-palette="cool"]', cool))

    head = ("/* GENERATED by tools/theme.py from [extra.theme] in config.toml.\n"
            "   Do not edit: the next run overwrites it. Change the values in\n"
            "   config.toml, or in the studio panel, and run the tool.\n"
            "\n"
            "   Linked after site.css, so what is here wins and what is left\n"
            "   blank keeps the stylesheet's own value. The cool palette's\n"
            "   DARK variant is not here: it is paired with the light one in\n"
            "   site.css, and a half-changed pair is worse than neither. */\n")
    if not rules:
        return head + "\n/* Nothing decided yet. */\n"
    body = "\n\n".join(f"{sel} {{\n" + "\n".join(lines) + "\n}"
                       for sel, lines in rules)
    return head + "\n" + body + "\n"


ALLOWED_SELECTORS = (":root", '[data-palette="cool"]')


def malformed(css: str) -> str:
    """What the shipped file must not contain.

    Independent of how it was built. The input validation above decides
    what goes in; this looks at what came out, because the thing that
    ships is the file.
    """
    body = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    if "@" in body or "url(" in body:
        return "the stylesheet contains an @-rule or a url(), and may hold "\
               "only custom properties"
    opens, closes = body.count("{"), body.count("}")
    if opens != closes:
        return f"{opens} opening braces against {closes} closing — a rule is "\
               f"unbalanced, which is how one rule becomes two"
    for rule in re.finditer(r"([^{}]*)\{([^{}]*)\}", body):
        selector = rule.group(1).strip()
        if selector not in ALLOWED_SELECTORS:
            return f"the stylesheet styles {selector!r}, and may style only "\
                   f"{' and '.join(ALLOWED_SELECTORS)}"
        for line in rule.group(2).strip().splitlines():
            line = line.strip()
            if line and not line.startswith("--"):
                return f"{line!r} is not a custom property. This file may set "\
                       f"tokens and nothing else"
    return ""


def main(argv: "list[str]") -> int:
    try:
        made = build()
    except Bad as no:
        print(f"\n  THEME REFUSED\n\n    - {no}\n", file=sys.stderr)
        return 1

    if "--check" in argv:
        on_disk = SHEET.read_text(encoding="utf-8") if SHEET.exists() else ""
        if on_disk != made:
            print("\n  static/css/theme.css does not match [extra.theme] in "
                  "config.toml.\n\n    Fix it with: python3 tools/theme.py\n",
                  file=sys.stderr)
            return 1
        shape = malformed(on_disk)
        if shape:
            print(f"\n  THEME STYLESHEET IS WRONG\n\n    - {shape}\n",
                  file=sys.stderr)
            return 1
        decided = made.count("--")
        print(f"\n  theme: the committed stylesheet matches config.toml and "
              f"holds nothing but tokens ({decided} value(s) decided)\n")
        return 0

    SHEET.parent.mkdir(parents=True, exist_ok=True)
    SHEET.write_text(made, encoding="utf-8")
    print(f"\n  wrote {SHEET.relative_to(ROOT)} "
          f"({made.count('--')} value(s) decided)\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
