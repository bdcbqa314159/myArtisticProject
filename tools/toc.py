#!/usr/bin/env python3
"""A way into the stylesheet.

    python3 tools/toc.py            # write the contents block into site.css
    python3 tools/toc.py --check    # fail if it no longer matches the file

WHY

`static/css/site.css` is 2800 lines and will stay one file: it is one
page, the cascade order is load-bearing, and splitting it would trade a
morning's readability for the class of bug the duplicate-selector
invariant exists to catch — a rule that silently stops applying because
something moved.

What it lacked was a way in. Its first 639 lines carried no heading at
all, and 786 more sat after the PRINT banner, so the only way to find
anything was to scroll and recognise it.

So: a contents block at the top, listing every section in the order
they appear, with the line each begins at and how long it is. Generated
from the banners themselves rather than written by hand, because a
hand-written index is a second copy of the truth and goes stale the
first time someone inserts a section — which is exactly how the file
got into this state.

THE LINE NUMBERS ARE THE POINT, and they are also why this is a tool
rather than a comment. They move with every edit above them; `--check`
fails when they have, and one run puts them right.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHEET = ROOT / "static" / "css" / "site.css"

OPEN = "/* ---- CONTENTS "
CLOSE = "   ---- end of contents "

BANNER = re.compile(r"^/\* ={10,}\s*$")


def sections(lines: "list[str]") -> "list[tuple[int, str]]":
    """Every banner, as (line number, title).

    A banner is a line of `=` and the title on the line after it. The
    title is taken up to its first em dash, so the long explanations
    under them do not become index entries.
    """
    found = []
    for i, line in enumerate(lines):
        if not BANNER.match(line):
            continue
        for ahead in lines[i + 1:i + 4]:
            if ahead.strip() and not ahead.strip().startswith("="):
                title = ahead.strip().rstrip("*/").strip()
                title = re.split(r"\s+[—-]\s+", title)[0].strip()
                found.append((i + 1, title))
                break
    return found


def block(lines: "list[str]") -> str:
    """The contents, as a comment to sit at the top of the file."""
    found = sections(lines)
    if not found:
        raise SystemExit("\n  no section banners found in site.css\n")

    ends = [n for n, _t in found[1:]] + [len(lines) + 1]
    width = max(len(t) for _n, t in found)
    rows = [
        f"   {title.ljust(width)}  {start:>5}  {end - start:>6}\n"
        for (start, title), end in zip(found, ends)
    ]
    return (
        f"{OPEN}{'-' * 58}\n"
        "   Generated by tools/toc.py from the banners below. Do not edit:\n"
        "   the next run overwrites it, and `--check` fails while it is\n"
        "   stale. One file on purpose — the cascade order is load-bearing.\n"
        "\n"
        f"   {'section'.ljust(width)}  {'line':>5}  {'lines':>6}\n"
        f"   {'-' * width}  -----  ------\n"
        + "".join(rows)
        + f"{CLOSE}{'-' * 54} */\n"
    )


def rewritten() -> str:
    text = SHEET.read_text(encoding="utf-8")

    # The file's own opening comment stays first; the contents go under
    # it, because the first thing to read is what the file is FOR.
    head = text.index(" */\n") + len(" */\n")
    body = text[head:]
    if OPEN in body:
        body = body[body.index("*/", body.index(CLOSE)) + 3:]
    body = body.lstrip("\n")

    # Measured against the file as it will be, not as it was: inserting
    # the block moves every line below it, so the numbers have to be
    # computed from the result. Two passes settle it — the block's own
    # height does not change once its rows are known.
    made = block((text[:head] + "\n" + body).splitlines())
    for _ in range(3):
        candidate = text[:head] + "\n" + made + "\n" + body
        again = block(candidate.splitlines())
        if again == made:
            return candidate
        made = again
    raise SystemExit("\n  the contents block will not settle\n")


def main(argv: "list[str]") -> int:
    made = rewritten()
    if "--check" in argv:
        if SHEET.read_text(encoding="utf-8") != made:
            print("\n  the contents block at the top of static/css/site.css is "
                  "out of date.\n\n    Fix it with: python3 tools/toc.py\n",
                  file=sys.stderr)
            return 1
        n = len(sections(made.splitlines()))
        print(f"\n  contents: {n} sections, every line number correct\n")
        return 0

    SHEET.write_text(made, encoding="utf-8")
    found = sections(made.splitlines())
    print(f"\n  wrote the contents of static/css/site.css — {len(found)} "
          f"sections\n")
    ends = [n for n, _t in found[1:]] + [len(made.splitlines()) + 1]
    for (start, title), end in sorted(
            zip(found, ends), key=lambda r: r[0][0] - r[1], reverse=True)[:5]:
        print(f"    {end - start:5} lines  {title}")
    print()
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
